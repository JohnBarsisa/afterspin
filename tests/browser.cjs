/* Serve the repo on port 5190, then run with Playwright and Chromium installed. */
const {chromium}=require('playwright');
const {strict:a}=require('node:assert');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 try{
 const desktop=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
 const page=await desktop.newPage(), rootUrl=process.env.AFTERSPIN_URL||'http://127.0.0.1:5190/';
 const errors=[];page.on('pageerror',x=>errors.push(String(x)));
 await page.goto(rootUrl,{waitUntil:'networkidle'});
 a.equal(await page.title(),'Afterspin — Your listening, on repeat');
 a(await page.locator('.ribbon').evaluate(x=>x.complete&&x.naturalWidth>0));
 a.equal(await page.locator('#recap').isVisible(),false);
 a.equal(await page.locator('.stat').count(),0);
 await page.getByRole('button',{name:/mode/}).click();
 const mode=await page.locator('html').getAttribute('data-mode');
 await page.getByRole('combobox',{name:'Color palette'}).selectOption('forest');
 await page.reload();
 a.equal(await page.locator('html').getAttribute('data-palette'),'forest');
 a.equal(await page.locator('html').getAttribute('data-mode'),mode);
 await page.getByRole('button',{name:'Spotify',exact:true}).click();
 await page.getByRole('link',{name:'Open Spotify Wrapped'}).waitFor();
 a.equal(await page.locator('input[type=password]').count(),0);
 await page.getByRole('button',{name:'Close source settings'}).click();
 await page.getByRole('button',{name:'Apple Music',exact:true}).click();
 await page.getByRole('link',{name:'Open Apple Music Replay'}).waitFor();
 await page.getByText('Use a listening history file instead').click();
 await page.locator('#importFiles').setInputFiles(path.join(__dirname,'../fixtures/apple-history.csv'));
 await page.getByRole('button',{name:'Import listening history'}).click();
 await page.locator('#recap').waitFor({state:'visible'});
 a.equal(await page.locator('#sourceTag').textContent(),'IMPORTED HISTORY');
 const plays=()=>page.locator('.stat').nth(1).locator('strong').textContent();
 a.equal(await plays(),'3');
 await page.getByRole('button',{name:'Custom',exact:true}).click();
 await page.getByLabel('From',{exact:true}).fill('2026-11-17');
 await page.getByLabel('To',{exact:true}).fill('2026-11-17');
 await page.getByRole('button',{name:'Apply dates'}).click();
 a.equal(await plays(),'1');
 await page.getByRole('button',{name:'Play my recap'}).click();
 a.equal(await page.locator('#storyStage h3').textContent(),'You hit repeat.');
 await page.keyboard.press('ArrowRight');
 a.match(await page.locator('#storyStatus').textContent(),/Chapter 2 of 5/);
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download card'}).click();
 a.equal(await (await download).failure(),null);
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Manage music source'}).click();
 await page.getByRole('button',{name:'Remove my data from Afterspin'}).click();
 await page.getByRole('button',{name:'Close source settings'}).click();
 a.equal(await page.locator('#recap').isVisible(),false);
 a.deepEqual(errors,[]);
 const mobile=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true,reducedMotion:'reduce'});
 const phone=await mobile.newPage();await phone.goto(rootUrl);
 a.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 a(await phone.locator('.ribbon').evaluate(e=>getComputedStyle(e).animationName==='none'));
 await phone.getByRole('button',{name:'Apple Music',exact:true}).click();
 a(await phone.getByRole('link',{name:'Open Apple Music Replay'}).isVisible());
 console.log('Browser checks passed: public landing, providers, themes, import, recap, PNG and mobile layout.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
